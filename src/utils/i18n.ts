export type TranslationKey = keyof typeof DICTIONARY;

export function t(key: TranslationKey, lang: SupportedLang = 'bn'): string {
  const item = DICTIONARY[key];
  if (!item) return key;
  return item[lang] || item['bn'] || key;
}

// Convert numbers between English and Bengali digits
export function toLangNumber(val: number | string | undefined | null, lang: SupportedLang = 'bn'): string {
  if (val === undefined || val === null) return '';
  if (typeof val === 'number' && (isNaN(val) || !isFinite(val))) return lang === 'bn' ? '০' : '0';
  const rawStr = String(val).trim();
  if (!rawStr || rawStr === 'null' || rawStr === 'undefined') return '';
  if (rawStr === 'NaN') return lang === 'bn' ? '০' : '0';

  // Sanitize any literal NaN in string
  const str = rawStr.replace(/NaN/g, '০').replace(/null/g, '').replace(/undefined/g, '');

  if (lang === 'en') {
    const bnToEnMap: Record<string, string> = {
      '০': '0', '১': '1', '২': '2', '৩': '3', '৪': '4',
      '৫': '5', '৬': '6', '৭': '7', '৮': '8', '৯': '9'
    };
    return str.replace(/[০-৯]/g, d => bnToEnMap[d] || d);
  } else {
    const enToBnMap: Record<string, string> = {
      '0': '০', '1': '১', '2': '২', '3': '৩', '4': '৪',
      '5': '৫', '6': '৬', '7': '৭', '8': '৮', '9': '৯'
    };
    return str.replace(/[0-9]/g, d => enToBnMap[d] || d);
  }
}

// Format date string into human-readable date without NaN
export function formatLangDate(dateStr: string | undefined | null, lang: SupportedLang = 'bn'): string {
  if (!dateStr) return lang === 'bn' ? 'তারিখ নির্ধারিত হয়নি' : 'Date not set';
  
  const rawTrimmed = String(dateStr).trim();
  if (rawTrimmed === '' || rawTrimmed === 'null' || rawTrimmed === 'undefined' || rawTrimmed === 'NaN') {
    return lang === 'bn' ? 'তারিখ নির্ধারিত হয়নি' : 'Date not set';
  }

  // Convert any Bengali digits to English for clean parsing
  const bnToEnMap: Record<string, string> = {
    '০': '0', '১': '1', '২': '2', '৩': '3', '৪': '4',
    '৫': '5', '৬': '6', '৭': '7', '৮': '8', '৯': '9'
  };
  const englishDigitsDate = rawTrimmed.replace(/[০-৯]/g, d => bnToEnMap[d] || d);

  try {
    const bnMonths = ['জানুয়ারি', 'ফেব্রুয়ারি', 'মার্চ', 'এপ্রিল', 'মে', 'জুন', 'জুলাই', 'আগস্ট', 'সেপ্টেম্বর', 'অক্টোবর', 'নভেম্বর', 'ডিসেম্বর'];
    const enMonths = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

    const dateOnly = englishDigitsDate.split(/[T ]/)[0].replace(/[,.]/g, '');
    const delimiter = dateOnly.includes('-') ? '-' : (dateOnly.includes('/') ? '/' : null);

    if (delimiter) {
      const parts = dateOnly.split(delimiter).map(p => parseInt(p, 10));
      if (parts.length === 3 && parts.every(n => !isNaN(n))) {
        let year: number;
        let monthIdx: number;
        let day: number;

        // Check if YYYY-MM-DD or DD-MM-YYYY
        if (parts[0] > 1900) {
          year = parts[0];
          monthIdx = parts[1] - 1;
          day = parts[2];
        } else if (parts[2] > 1900) {
          day = parts[0];
          monthIdx = parts[1] - 1;
          year = parts[2];
        } else {
          year = parts[0] > 31 ? parts[0] : parts[2];
          monthIdx = parts[1] - 1;
          day = parts[0] > 31 ? parts[2] : parts[0];
        }

        if (monthIdx >= 0 && monthIdx <= 11 && day >= 1 && day <= 31 && year >= 1970 && year <= 2100) {
          if (lang === 'bn') {
            const dayStr = toLangNumber(String(day).padStart(2, '0'), 'bn');
            const yearStr = toLangNumber(String(year), 'bn');
            const monthName = bnMonths[monthIdx];
            return `${dayStr} ${monthName} ${yearStr}`;
          } else {
            const dayStr = String(day).padStart(2, '0');
            const monthName = enMonths[monthIdx];
            return `${dayStr} ${monthName} ${year}`;
          }
        }
      }
    }

    // Attempt JavaScript Date object parsing
    const parsedObj = new Date(englishDigitsDate);
    if (!isNaN(parsedObj.getTime())) {
      const day = parsedObj.getDate();
      const monthIdx = parsedObj.getMonth();
      const year = parsedObj.getFullYear();
      if (lang === 'bn') {
        const dayStr = toLangNumber(String(day).padStart(2, '0'), 'bn');
        const yearStr = toLangNumber(String(year), 'bn');
        const monthName = bnMonths[monthIdx];
        return `${dayStr} ${monthName} ${yearStr}`;
      } else {
        const dayStr = String(day).padStart(2, '0');
        const monthName = enMonths[monthIdx];
        return `${dayStr} ${monthName} ${year}`;
      }
    }

    // Fallback: return sanitized string
    const cleanOutput = toLangNumber(rawTrimmed, lang)
      .replace(/NaN/g, '')
      .replace(/null/g, '')
      .replace(/undefined/g, '')
      .trim();

    return cleanOutput || (lang === 'bn' ? 'তারিখ নির্ধারিত হয়নি' : 'Date not set');
  } catch {
    return toLangNumber(rawTrimmed, lang).replace(/NaN/g, '').replace(/null/g, '').trim() || (lang === 'bn' ? 'তারিখ নির্ধারিত হয়নি' : 'Date not set');
  }
}

// Format date and time into human-readable, dignified string without NaN
export function formatLangDateTime(dateStr: string | undefined | null, lang: SupportedLang = 'bn'): string {
  if (!dateStr) return lang === 'bn' ? 'তারিখ নির্ধারিত হয়নি' : 'Date not set';
  
  const rawTrimmed = String(dateStr).trim();
  if (rawTrimmed === '' || rawTrimmed === 'null' || rawTrimmed === 'undefined' || rawTrimmed === 'NaN') {
    return lang === 'bn' ? 'তারিখ নির্ধারিত হয়নি' : 'Date not set';
  }

  // Convert Bengali numbers to English
  const bnToEnMap: Record<string, string> = {
    '০': '0', '১': '1', '২': '2', '৩': '3', '৪': '4',
    '৫': '5', '৬': '6', '৭': '7', '৮': '8', '৯': '9'
  };
  const englishDigitsDate = rawTrimmed.replace(/[০-৯]/g, d => bnToEnMap[d] || d);

  try {
    const bnMonths = ['জানুয়ারি', 'ফেব্রুয়ারি', 'মার্চ', 'এপ্রিল', 'মে', 'জুন', 'জুলাই', 'আগস্ট', 'সেপ্টেম্বর', 'অক্টোবর', 'নভেম্বর', 'ডিসেম্বর'];
    const enMonths = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

    if (englishDigitsDate.includes('T') || englishDigitsDate.includes(' ')) {
      const parts = englishDigitsDate.split(/[T ]/);
      const dateParts = parts[0].split('-').map(p => parseInt(p, 10));
      const timeParts = (parts[1] || '09:00').split(':').map(p => parseInt(p, 10));

      const year = dateParts[0];
      const monthIdx = dateParts[1] - 1;
      const day = dateParts[2];
      const hour = !isNaN(timeParts[0]) ? timeParts[0] : 9;
      const min = !isNaN(timeParts[1]) ? timeParts[1] : 0;

      if (!isNaN(year) && !isNaN(monthIdx) && !isNaN(day) && monthIdx >= 0 && monthIdx <= 11) {
        if (lang === 'bn') {
          const period = hour < 12 ? 'সকাল' : (hour === 12 ? 'দুপুর' : (hour < 16 ? 'দুপুর' : (hour < 19 ? 'বিকাল' : 'রাত')));
          const displayHour = hour > 12 ? hour - 12 : (hour === 0 ? 12 : hour);
          const hourStr = toLangNumber(String(displayHour).padStart(2, '0'), 'bn');
          const minStr = toLangNumber(String(min).padStart(2, '0'), 'bn');
          const dayStr = toLangNumber(String(day).padStart(2, '0'), 'bn');
          const yearStr = toLangNumber(String(year), 'bn');
          const monthName = bnMonths[monthIdx];

          return `${dayStr} ${monthName} ${yearStr} ইং, ${period} ${hourStr}:${minStr} টা`;
        } else {
          const ampm = hour >= 12 ? 'PM' : 'AM';
          const displayHour = hour % 12 || 12;
          const hourStr = String(displayHour).padStart(2, '0');
          const minStr = String(min).padStart(2, '0');
          const dayStr = String(day).padStart(2, '0');
          const monthName = enMonths[monthIdx];

          return `${dayStr} ${monthName} ${year} at ${hourStr}:${minStr} ${ampm}`;
        }
      }
    }

    return formatLangDate(dateStr, lang);
  } catch {
    return formatLangDate(dateStr, lang);
  }
}

